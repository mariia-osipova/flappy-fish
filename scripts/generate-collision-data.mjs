import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { inflateSync } from "node:zlib";

const imagePath = new URL("../data/img/fish1.png", import.meta.url);
const outputPath = new URL("../src/shared/collision-data.js", import.meta.url);
const ALPHA_THRESHOLD = 32;

function paeth(left, up, upperLeft) {
  const predicted = left + up - upperLeft;
  const a = Math.abs(predicted - left);
  const b = Math.abs(predicted - up);
  const c = Math.abs(predicted - upperLeft);
  return a <= b && a <= c ? left : b <= c ? up : upperLeft;
}

// The source sprite is an ordinary, non-interlaced RGBA PNG. Keep this build
// helper independent of browser canvas and native image-processing packages.
function decodeRgbaPng(png) {
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  if (!png.subarray(0, 8).equals(signature)) throw new Error("Invalid PNG signature");

  let width;
  let height;
  const compressed = [];
  for (let offset = 8; offset + 12 <= png.length;) {
    const length = png.readUInt32BE(offset);
    const type = png.toString("ascii", offset + 4, offset + 8);
    if (offset + length + 12 > png.length) throw new Error("Truncated PNG chunk");
    const chunk = png.subarray(offset + 8, offset + 8 + length);
    if (type === "IHDR") {
      if (length !== 13 || chunk[8] !== 8 || chunk[9] !== 6
          || chunk[10] !== 0 || chunk[11] !== 0 || chunk[12] !== 0) {
        throw new Error("Expected an 8-bit, non-interlaced RGBA PNG");
      }
      width = chunk.readUInt32BE(0);
      height = chunk.readUInt32BE(4);
    } else if (type === "IDAT") {
      compressed.push(chunk);
    }
    offset += length + 12;
    if (type === "IEND") break;
  }
  if (!width || !height || width > 4096 || height > 4096 || !compressed.length) {
    throw new Error("Invalid sprite dimensions or image data");
  }

  const stride = width * 4;
  const raw = inflateSync(Buffer.concat(compressed), {
    maxOutputLength: (stride + 1) * height,
  });
  if (raw.length !== (stride + 1) * height) throw new Error("Invalid PNG scanline size");
  const pixels = Buffer.alloc(stride * height);
  for (let y = 0; y < height; y += 1) {
    const filter = raw[y * (stride + 1)];
    if (filter > 4) throw new Error("Unsupported PNG scanline filter");
    for (let x = 0; x < stride; x += 1) {
      const left = x >= 4 ? pixels[y * stride + x - 4] : 0;
      const up = y > 0 ? pixels[(y - 1) * stride + x] : 0;
      const upperLeft = y > 0 && x >= 4 ? pixels[(y - 1) * stride + x - 4] : 0;
      const predictor = filter === 0 ? 0
        : filter === 1 ? left
          : filter === 2 ? up
            : filter === 3 ? Math.floor((left + up) / 2)
              : paeth(left, up, upperLeft);
      pixels[y * stride + x] = (raw[y * (stride + 1) + x + 1] + predictor) & 255;
    }
  }
  return { width, height, pixels };
}

function literal(value) {
  return Object.is(value, -0) ? "-0" : String(value);
}

function buildRotationTable() {
  const velocities = new Set([0, -10, 100]);
  // Both origins are used by the existing game: a new fish starts at zero,
  // and a flap sets -10. Preserve repeated floating-point additions of 0.3.
  for (const origin of [0, -10]) {
    let velocity = origin;
    while (velocity < 100) {
      velocities.add(velocity);
      velocity += 0.3;
      if (velocity > 100) velocity = 100;
    }
  }
  return [...velocities].sort((a, b) => a - b).map((velocity) => {
    const angle = -Math.max(-30, Math.min(90, velocity * 3)) * Math.PI / 180;
    return `  ${JSON.stringify(String(velocity))}: Object.freeze([${[angle, Math.cos(angle), Math.sin(angle)].map(literal).join(", ")}]),`;
  }).join("\n");
}

async function generate() {
  const png = await readFile(imagePath);
  const { width, height, pixels } = decodeRgbaPng(png);
  const points = [];
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      if (pixels[(y * width + x) * 4 + 3] > ALPHA_THRESHOLD) points.push([x, y]);
    }
  }
  if (!points.length) throw new Error("The fish sprite has no collision pixels");
  const rotations = buildRotationTable();
  const imageHash = createHash("sha256").update(png).digest("hex");
  const dataHash = createHash("sha256")
    .update(JSON.stringify({ width, height, threshold: ALPHA_THRESHOLD, points }))
    .update(rotations)
    .digest("hex");
  return `// Generated by scripts/generate-collision-data.mjs; do not edit by hand.
// Changing this data changes ranked-game rules. Commit the regenerated file.
export const COLLISION_DATA_VERSION = ${JSON.stringify(dataHash)};
export const FISH_IMAGE_SHA256 = ${JSON.stringify(imageHash)};
export const FISH_IMAGE_WIDTH = ${width};
export const FISH_IMAGE_HEIGHT = ${height};
export const FISH_ALPHA_HIT_THRESHOLD = ${ALPHA_THRESHOLD};
export const FISH_HIT_PIXELS = Object.freeze([
${points.map((point) => `  Object.freeze([${point.join(", ")}]),`).join("\n")}
]);

// [angle, cos(angle), sin(angle)] for every reachable velocity. Runtime
// collision decisions never depend on a browser's transcendental functions.
export const FISH_ROTATIONS = Object.freeze({
${rotations}
});
`;
}

const args = process.argv.slice(2);
if (args.some((arg) => arg !== "--check") || args.length > 1) {
  throw new Error("Usage: node scripts/generate-collision-data.mjs [--check]");
}
const generated = await generate();
if (args.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== generated) {
    throw new Error("Collision data is stale; run node scripts/generate-collision-data.mjs");
  }
  console.log("Collision data matches the sprite and rotation generator.");
} else {
  await writeFile(outputPath, generated);
  console.log(`Generated ${fileURLToPath(outputPath)}`);
}
